-- ------------------------------------------------------------------ dates
-- local time as plain day numbers (days since 1970-01-01), no os.date needed
local function days_from_civil(y, m, d)
    if m <= 2 then y = y - 1 end
    local era = y // 400
    local yoe = y - era * 400
    local doy = (153 * (m > 2 and m - 3 or m + 9) + 2) // 5 + d - 1
    return era * 146097 + yoe * 365 + yoe // 4 - yoe // 100 + doy - 719468
end
local function civil(z) -- day number -> y, m, d
    z = z + 719468
    local era = z // 146097
    local doe = z - era * 146097
    local yoe = (doe - doe // 1460 + doe // 36524 - doe // 146096) // 365
    local doy = doe - (365 * yoe + yoe // 4 - yoe // 100)
    local mp = (5 * doy + 2) // 153
    local m = mp < 10 and mp + 3 or mp - 9
    return yoe + era * 400 + (m <= 2 and 1 or 0), m, doy - (153 * mp + 2) // 5 + 1
end
local function weekday(day) return (day + 3) % 7 + 1 end -- 1 = Monday
local function month_of(day) local y, m = civil(day); return y * 12 + m - 1 end

-- the band's clock comes from dataman; os.time() (UTC) only until it arrives
local clk = { y = 0, mo = 1, d = 1, h = 0, mi = 0, is24 = true, am = true }
local function hour24()
    if clk.is24 then return clk.h end
    return clk.h % 12 + (clk.am and 0 or 12)
end
local function now()
    if clk.y < 2000 then return os.time() end
    return days_from_civil(clk.y, clk.mo, clk.d) * 86400 + hour24() * 3600 + clk.mi * 60
end
local function today() return now() // 86400 end

-- ------------------------------------------------------------------ data
local entries = {} -- oldest first: { t, a (amount), c (category), n (note), day, mk, dom }

local function stamp(e)
    e.day = e.t // 86400
    local y, m, d = civil(e.day)
    e.mk, e.dom = y * 12 + m - 1, d
    return e
end

local load_ok, load_err = pcall(function()
    local f = io.open(SAVE, "r"); if not f then return end
    local all = f:read("*a") or ""; f:close()
    for line in all:gmatch("[^\r\n]+") do
        local t, a, c, n = line:match("^(%d+) (%d+) (%d+) ?(.*)$")
        if t and CATS[tonumber(c)] then
            entries[#entries + 1] = stamp { t = tonumber(t), a = tonumber(a), c = tonumber(c), n = n }
        end
    end
end)

local function line_of(e) return string.format("%d %d %d %s\n", e.t, e.a, e.c, e.n) end
local function append(e)
    return pcall(function() local f = assert(io.open(SAVE, "a")); f:write(line_of(e)); f:close() end)
end
local function rewrite()
    return pcall(function()
        local f = assert(io.open(SAVE, "w"))
        for _, e in ipairs(entries) do f:write(line_of(e)) end
        f:close()
    end)
end

local function sum(test)
    local s, n = 0, 0
    for _, e in ipairs(entries) do if test(e) then s, n = s + e.a, n + 1 end end
    return s, n
end
local function month_total(mk) return sum(function(e) return e.mk == mk end) end

local function commas(n)
    return (tostring(math.floor(n)):reverse():gsub("(%d%d%d)", "%1,"):reverse():gsub("^,", ""))
end
local function money(n) return CUR .. commas(n) end
local function clip(s, n) return #s > n and s:sub(1, n - 1) .. ".." or s end
local function hm(t)
    local h, m = t % 86400 // 3600, t % 3600 // 60
    if clk.is24 then return string.format("%02d:%02d", h, m) end
    return string.format("%d:%02d %s", (h + 11) % 12 + 1, m, h < 12 and "am" or "pm")
end

