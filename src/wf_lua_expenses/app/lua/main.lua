R.note = function()
    local ct = CATS[draft.c]
    text(n_amt, money(draft.a))
    text(n_cat, ct.name); color(n_cat, ct.color)
    text(n_text, draft.n == "" and "Tap to type a note" or draft.n)
    color(n_text, draft.n == "" and DIM or TEXT)
    -- your recent notes for this category first, then the presets
    local list, have = {}, {}
    for k = #entries, 1, -1 do
        local e = entries[k]
        if #list >= 4 then break end
        if e.c == draft.c and e.n ~= "" and not have[e.n] then list[#list + 1] = e.n; have[e.n] = true end
    end
    for _, s in ipairs(ct.notes) do
        if #list >= 8 then break end
        if not have[s] then list[#list + 1] = s; have[s] = true end
    end
    for i, ch in ipairs(chips) do
        ch.note = list[i] or ""
        show(ch.obj, ch.note ~= "")
        text(ch.label, clip(ch.note, 14))
        ch.recolor(ch.note == draft.n and ACCENT_SOFT or KEY)
    end
end

