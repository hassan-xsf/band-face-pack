-- cached setters: only talk to lvgl when something changed
local seen = setmetatable({}, { __mode = "k" })
local texts = setmetatable({}, { __mode = "k" }) -- glyph text objects (plain tables)
local function put(o, k, v)
    local c = seen[o]; if not c then c = {}; seen[o] = c end
    if c[k] ~= v then c[k] = v; o:set { [k] = v } end
end
local function show(o, on)
    if texts[o] then o = o.o end
    local c = seen[o]; if not c then c = {}; seen[o] = c end
    if c.shown ~= on then
        c.shown = on
        if on then o:clear_flag(lvgl.FLAG.HIDDEN) else o:add_flag(lvgl.FLAG.HIDDEN) end
    end
end

