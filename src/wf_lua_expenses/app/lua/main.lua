R.month = function()
    local now_mk = month_of(today())
    sel_mk = math.min(sel_mk, now_mk)
    local total, count = month_total(sel_mk)
    text(m_title, MONTHS[sel_mk % 12 + 1] .. " " .. sel_mk // 12)
    big(m_total, money(total))
    local prev = month_total(sel_mk - 1)
    local s = count == 0 and "No expenses" or (count .. (count == 1 and " expense" or " expenses"))
    if prev > 0 and count > 0 and sel_mk < now_mk then
        s = s .. string.format(", %d%% %s than %s", math.floor(math.abs(total - prev) * 100 / prev + 0.5),
            total > prev and "more" or "less", MONTHS[(sel_mk - 1) % 12 + 1]:sub(1, 3))
    end
    text(m_sub, s)
    show(m_next.obj, sel_mk < now_mk)

    local last = sel_mk > now_mk - 6 and now_mk or sel_mk
    local tot, most = {}, 0
    for i = 1, 6 do tot[i] = month_total(last - 6 + i); most = math.max(most, tot[i]) end
    for i, col in ipairs(m_cols) do
        col.mk = last - 6 + i
        local h = most > 0 and tot[i] > 0 and math.max(6, math.floor(tot[i] * M_MAX / most + 0.5)) or 0
        set_bar(col.bar, 12, M_BOTTOM, h)
        put(col.bar, "bg_color", col.mk == sel_mk and ACCENT or ACCENT_SOFT)
        text(col.name, MONTHS[col.mk % 12 + 1]:sub(1, 3))
        color(col.name, col.mk == sel_mk and TEXT or DIM)
    end

    -- category split: stacked bar + the top four
    local by, order = {}, {}
    for i = 1, #CATS do by[i] = 0; order[i] = i end
    for _, e in ipairs(entries) do if e.mk == sel_mk then by[e.c] = by[e.c] + e.a end end
    table.sort(order, function(a, b) return by[a] > by[b] or (by[a] == by[b] and a < b) end)
    local x = 0
    for _, c in ipairs(order) do
        local w = total > 0 and math.floor(by[c] * 304 / total + 0.5) or 0
        w = math.min(w, 304 - x)
        show(segs[c], w > 0)
        if w > 0 then segs[c]:set { w = w, align = at(TL, x, 0) } end
        x = x + w
    end
    for i, row in ipairs(m_rows) do
        local c = order[i]
        local on = by[c] > 0
        for _, o in pairs(row) do show(o, on) end
        if on then
            put(row.dot, "bg_color", CATS[c].color)
            text(row.name, CATS[c].name)
            text(row.pct, math.floor(by[c] * 100 / total + 0.5) .. "%")
            text(row.am, money(by[c]))
        end
    end
end

-- ------------------------------------------------------------------ timer, clock, lifecycle
-- 100 ms ticks, only while a keypad letter is pending or a toast is up
local function tick()
    if pend then
        idle = idle + 1
        if idle >= 9 then pend = nil; if current == "type" then R.type() end end
    end
    if toast_left > 0 then
        toast_left = toast_left - 1
        if toast_left == 0 and current == "home" then R.home() end
    end
    if not pend and toast_left == 0 then timer:pause() end
end
timer = lvgl.Timer { period = 100, cb = function()
    local ok, err = pcall(tick); if not ok then report(err) end
end }
wake = function() timer:resume() end
timer:pause()

local ok_dm, dataman = pcall(require, "dataman")
if ok_dm and dataman then
    local shown_day
    local function changed()
        if current == "home" then
            -- full redraw only when the date moves; otherwise just the time
            if shown_day ~= today() then shown_day = today(); R.home() else text(h_time, hm(now())) end
        end
    end
    local function sub(name, set)
        pcall(dataman.subscribe, name, h_time, function(_, v)
            local ok, err = pcall(function() set(type(v) == "number" and v // 256 or v); changed() end)
            if not ok then report(err) end
        end)
    end
    sub("dateYear", function(v) clk.y = v end)
    sub("dateMonth", function(v) clk.mo = v end)
    sub("dateDay", function(v) clk.d = v end)
    sub("timeHour", function(v) clk.h = v end)
    sub("timeMinute", function(v) clk.mi = v end)
    sub("miscIs24H", function(v) clk.is24 = v ~= 0 end)
    sub("miscIsAM", function(v) clk.am = v ~= 0 end)
end

