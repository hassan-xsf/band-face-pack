local function lighten(c)
    local r, g, b = (c >> 16) & 255, (c >> 8) & 255, c & 255
    return (math.min(255, r + 26) << 16) | (math.min(255, g + 26) << 8) | math.min(255, b + 26)
end

-- tappable box: lightens while pressed, fn runs on a short tap only
local function button(parent, x, y, w, h, bg, radius, fn)
    local o = box(parent, x, y, w, h, bg, radius)
    o:add_flag(lvgl.FLAG.CLICKABLE)
    local b = { obj = o, base = bg }
    function b.recolor(c) b.base = c; put(o, "bg_color", c) end
    o:onevent(lvgl.EVENT.ALL, function(_, code)
        if code == lvgl.EVENT.PRESSED and b.base then put(o, "bg_color", lighten(b.base))
        elseif code == lvgl.EVENT.RELEASED or code == lvgl.EVENT.PRESS_LOST then
            if b.base then put(o, "bg_color", b.base) end
        elseif code == lvgl.EVENT.SHORT_CLICKED then
            local ok, err = pcall(fn); if not ok then report(err) end
        end
    end)
    return b
end
local function pill(parent, x, y, w, h, bg, s, col, fn)
    local b = button(parent, x, y, w, h, bg, h // 2, fn)
    b.label = label(b.obj, s, 19, col or TEXT, C, 0, 0)
    return b
end

