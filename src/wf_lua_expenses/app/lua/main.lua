local T9 = { ".,-'!?1", "abc2", "def3", "ghi4", "jkl5", "mno6", "pqrs7", "tuv8", "wxyz9", nil, " 0", nil }
local TOPS = { ". , -", "abc", "def", "ghi", "jkl", "mno", "pqrs", "tuv", "wxyz" }
local pend, pend_i, idle = nil, 1, 0
local t_keys = {}

local function cased(ch, pos) return pos == 1 and ch:upper() or ch end
local function type_key(i)
    if i == 10 then
        pend = nil; draft.n = draft.n:sub(1, -2)
    elseif i == 12 then
        pend = nil; draft.n = draft.n:gsub("^%s+", ""):gsub("%s+$", ""); go("note"); return
    elseif pend == i then -- same key again: next letter in place
        pend_i = pend_i % #T9[i] + 1
        draft.n = draft.n:sub(1, -2) .. cased(T9[i]:sub(pend_i, pend_i), #draft.n)
        idle = 0
    elseif #draft.n < NOTE_MAX then
        pend, pend_i, idle = i, 1, 0
        draft.n = draft.n .. cased(T9[i]:sub(1, 1), #draft.n + 1)
        wake()
    end
    R.type()
end
for i = 1, 12 do
    local c, r = (i - 1) % 3, (i - 1) // 3
    local b = button(typ, 16 + c * 104, 126 + r * 64, 96, 58, i == 12 and ACCENT or KEY, 29, function() type_key(i) end)
    if i == 10 then icon(b.obj, "i_del", C)
    elseif i == 11 then label(b.obj, "space", 18, SUB, C, 0, 0)
    elseif i == 12 then label(b.obj, "Done", 19, TEXT, C, 0, 0)
    else
        label(b.obj, TOPS[i], 21, TEXT, C, 0, -7)
        label(b.obj, T9[i]:sub(-1), 13, SUB, C, 0, 15)
    end
    t_keys[i] = b
end

