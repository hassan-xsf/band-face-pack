-- plain boxes never take touches: they pass them up to the band
local function box(parent, x, y, w, h, bg, radius, align)
    local o = lvgl.Object(parent, {
        w = w, h = h, bg_color = bg or BG, bg_opa = lvgl.OPA(bg and 100 or 0), radius = radius or 0,
        border_width = 0, pad_all = 0, align = at(align or TL, x, y),
    })
    o:clear_flag(lvgl.FLAG.SCROLLABLE)
    o:clear_flag(lvgl.FLAG.CLICKABLE)
    o:add_flag(lvgl.FLAG.EVENT_BUBBLE)
    return o
end
-- text is Chakra Petch glyph images (gen_assets.py), white, so any colour works:
-- greys are white at lower opacity, colours use img_recolor (white if unsupported)
local PAD = 2 -- glyph images have 2 px of room on each side
local SHADE = { [TEXT] = 255, [SUB] = 150, [DIM] = 80 }
local function tint(im, col)
    local a = SHADE[col]
    put(im, "img_opa", a or 255)
    pcall(put, im, "img_recolor_opa", a and 0 or 255)
    if not a then pcall(put, im, "img_recolor", col) end
end
local function render(t)
    if t.shown_s == t.s and t.shown_col == t.col then return end
    t.shown_s, t.shown_col = t.s, t.col
    local g, x, n = t.g, 0, 0
    for i = 1, #t.s do
        local b = t.s:byte(i)
        if not g.adv[b] then b = g.adv[63] and 63 end -- unknown -> "?", or skip in digit-only styles
        if b then
            if b ~= 32 then
                n = n + 1
                local file = DIR .. t.st .. b .. ".png"
                local im = t.ims[n]
                if not im then im = t.o:Image { src = file }; t.ims[n] = im end
                put(im, "src", file)
                put(im, "x", math.floor(x + 0.5) - PAD)
                show(im, true)
                tint(im, t.col)
            end
            x = x + g.adv[b]
        end
    end
    for k = n + 1, #t.ims do show(t.ims[k], false) end
    put(t.o, "w", math.ceil(x) + 1)
end
-- styles: h 46 (amounts), k 28 (amounts), m 19, s 14
local function label(parent, s, px, col, align, x, y)
    local st = px >= 40 and "h" or px >= 24 and "k" or px >= 17 and "m" or "s"
    local t = { st = st, g = GLYPHS[st], ims = {}, s = s, col = col }
    t.o = box(parent, x, y, 0, t.g.h, nil, 0, align)
    texts[t] = true
    render(t)
    return t
end
