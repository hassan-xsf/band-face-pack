# Renders everything the face draws as images into app/lua:
#   * icons: Material Symbols Sharp (fonts/), category tiles pre-tinted
#   * text: Chakra Petch glyphs, white, one tiny PNG per character per style;
#     main.lua tints them and places them using the advances written into its
#     "@glyphs" block below. Kept small: 4 styles, the big ones digits only.
# Run: python gen_assets.py
import math
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).parent
OUT = HERE / "app" / "lua"
FONTS = HERE.parent.parent / "fonts"
SYMBOLS = str(FONTS / "MaterialSymbolsSharp.ttf")
ASCII = "".join(chr(c) for c in range(33, 127))
STYLES = {  # key: (weight, px, chars)
    "h": ("SemiBold", 46, "Rs0123456789,"),
    "k": ("SemiBold", 28, "Rs0123456789,"),
    "m": ("SemiBold", 19, ASCII),
    "s": ("Medium", 14, ASCII),
}
CATS = [  # icon codepoint, colour (same order as CATS in main.lua)
    (0xE56C, 0xFF9F0A), (0xE559, 0x0A84FF), (0xF1CC, 0xFF375F), (0xEA0B, 0xFFD60A),
    (0xE8CC, 0x30D158), (0xF109, 0x64D2FF), (0xEA28, 0xBF5AF2), (0xE72C, 0x98989F),
]
SS = 4

for old in OUT.glob("*.png"):
    old.unlink()


def rgb(c): return (c >> 16 & 255, c >> 8 & 255, c & 255)


def symbol(cp, px, fill=1):
    f = ImageFont.truetype(SYMBOLS, px * SS)
    f.set_variation_by_axes([fill, 0, 40, 500])
    return f, chr(cp)


def icon(name, cp, px, color=(255, 255, 255), fill=1):
    f, ch = symbol(cp, px, fill)
    img = Image.new("RGBA", (px * SS, px * SS), color + (0,))
    ImageDraw.Draw(img).text((px * SS / 2, px * SS / 2), ch, font=f, fill=color + (255,), anchor="mm")
    img.resize((px, px), Image.LANCZOS).save(OUT / f"{name}.png")


def tile(name, cp, color, side, px, radius):
    s = side * SS
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([0, 0, s - 1, s - 1], radius * SS, fill=tuple(int(v * 0.2) for v in rgb(color)) + (255,))
    f, ch = symbol(cp, px)
    d.text((s / 2, s / 2), ch, font=f, fill=rgb(color) + (255,), anchor="mm")
    img.resize((side, side), Image.LANCZOS).save(OUT / f"{name}.png")


for i, (cp, col) in enumerate(CATS, 1):
    tile(f"cat{i}", cp, col, 40, 24, 12)
    tile(f"catxl{i}", cp, col, 76, 44, 22)
icon("i_list", 0xEF6E, 28)
icon("i_chart", 0xE26B, 28)
icon("i_add", 0xE145, 26)
icon("i_del", 0xE14A, 28, fill=0)
for name, cp in (("i_left", 0xE5CB), ("i_right", 0xE5CC), ("i_up", 0xE5CE), ("i_down", 0xE5CF)):
    icon(name, cp, 26)

# text glyphs + metrics
PAD = 2
lua = []
for key, (weight, px, chars) in STYLES.items():
    f = ImageFont.truetype(str(FONTS / f"ChakraPetch-{weight}.ttf"), px)
    asc, desc = f.getmetrics()
    h = asc + desc
    adv = {}
    for ch in " " + chars:
        a = f.getlength(ch)
        adv[ord(ch)] = round(a, 1)
        if ch == " ":
            continue
        img = Image.new("RGBA", (math.ceil(a) + 2 * PAD, h), (255, 255, 255, 0))
        ImageDraw.Draw(img).text((PAD, asc), ch, font=f, fill=(255, 255, 255, 255), anchor="ls")
        img.save(OUT / f"{key}{ord(ch)}.png", optimize=True)
    pairs = ", ".join(f"[{c}]={a:g}" for c, a in sorted(adv.items()))
    lua.append(f"    {key} = {{ h = {h}, adv = {{ {pairs} }} }},")

main = OUT / "main.lua"
src = main.read_text(encoding="utf-8")
block = "-- @glyphs (generated by gen_assets.py)\nlocal GLYPHS = {\n" + "\n".join(lua) + "\n}\n-- @glyphs end"
src = re.sub(r"-- @glyphs \(generated.*?-- @glyphs end", lambda _: block, src, flags=re.S)
main.write_text(src, encoding="utf-8", newline="\n")
files = list(OUT.glob("*.png"))
print("ok", len(files), "images,", sum(p.stat().st_size for p in files) // 1024, "KB")
